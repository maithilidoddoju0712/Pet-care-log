-- Pet Care Log database schema for Supabase PostgreSQL
create table if not exists public.pets (
  id bigint generated by default as identity primary key,
  name varchar(80) not null check (length(trim(name)) > 0),
  species varchar(20) not null check (species in ('Dog','Cat','Bird','Rabbit','Fish','Other')),
  breed varchar(80),
  birth_date date,
  weight_kg numeric(7,2) check (weight_kg is null or weight_kg between 0 and 1000),
  notes varchar(1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.care_logs (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  activity_type varchar(20) not null check (activity_type in ('Feeding','Walk','Exercise','Grooming','Playtime','Other')),
  activity_date date not null,
  notes varchar(1000),
  created_at timestamptz not null default now()
);
create table if not exists public.health_records (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  record_type varchar(20) not null check (record_type in ('Vaccination','Vet visit','Medication','Dental care','Other')),
  record_date date not null,
  next_due_date date,
  notes varchar(1000),
  created_at timestamptz not null default now(),
  check (next_due_date is null or next_due_date >= record_date)
);
create index if not exists care_logs_pet_date_idx on public.care_logs(pet_id, activity_date desc);
create index if not exists health_records_pet_date_idx on public.health_records(pet_id, record_date desc);
create index if not exists health_records_due_date_idx on public.health_records(next_due_date) where next_due_date is not null;
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists pets_set_updated_at on public.pets;
create trigger pets_set_updated_at before update on public.pets
for each row execute function public.set_updated_at();

-- This student MVP uses a server-only Supabase service-role key and performs
-- database operations through Express. Never put that key in browser code.
-- The tables intentionally do not expose direct anonymous access. If you later
-- connect a browser directly to Supabase, design and test per-user RLS policies
-- before enabling any client access.
alter table public.pets enable row level security;
alter table public.care_logs enable row level security;
alter table public.health_records enable row level security;
